SELECT COUNT(*) AS jobs FROM jobs;
SELECT title,COUNT(*) n FROM jobs GROUP BY title ORDER BY n DESC LIMIT 20;
SELECT company,COUNT(*) n FROM jobs WHERE company<>'' GROUP BY company ORDER BY n DESC LIMIT 20;
SELECT location,COUNT(*) n FROM jobs WHERE location<>'' GROUP BY location ORDER BY n DESC LIMIT 20;
SELECT skill,COUNT(*) n FROM skills GROUP BY skill ORDER BY n DESC;
SELECT mode,COUNT(*) n FROM jobs GROUP BY mode;
SELECT min_exp,COUNT(*) n FROM jobs GROUP BY min_exp ORDER BY min_exp;
SELECT COUNT(*) n FROM jobs WHERE min_exp<=2;
SELECT company,COUNT(*) n FROM jobs WHERE min_exp<=2 AND company<>'' GROUP BY company ORDER BY n DESC LIMIT 20;
SELECT s.skill,COUNT(*) n FROM skills s JOIN jobs j USING(job_id) WHERE min_exp<=2 GROUP BY s.skill ORDER BY n DESC;
SELECT COUNT(salary_lpa) disclosed,COUNT(*) total FROM jobs;
