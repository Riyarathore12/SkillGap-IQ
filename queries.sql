SELECT s.skill,AVG(j.salary_lpa) mean_lpa,COUNT(j.salary_lpa) n FROM skills s JOIN jobs j USING(job_id) GROUP BY s.skill HAVING n>=5 ORDER BY mean_lpa DESC;
